// The academic grade list (grades R15, GRD-7.3): the record as terms oldest first, as on a transcript, with
// each course's credits, grade, letter, status and components, the term GPA and the cumulative GPA through
// each term on both scales. The printable page renders it; the record export writes it as CSV (UTF-8 with
// a byte-order mark) and JSON through a blob link (platform amendment: no `downloads`). Free of the FAP
// access layer, so the print page can import it.
import { semesterOrder } from './engine/gpa'
import { computeGpaOn, letterOf, pointsOf, type GpaScale, type Letter } from './engine/scale'
import { BOM, csvCell } from './export'
import { components, recordTerms, sheetStatusText, type RecordComponent } from './record-model'
import type { RecordStore } from './record'

export const NOT_OFFICIAL = 'Generated by FAP-AIO from FAP data; not an official transcript'

export interface Gpas { ten: number | null; four: number | null; credits: number }

export interface GradeListCourse {
  code: string | null
  name: string
  credits: number | null
  grade: number | null
  letter: Letter | null
  points: number | null
  status: string
  counted: boolean
  average: number | null
  sheetStatus: string | null
  components: RecordComponent[]
}

export interface GradeListTerm { name: string; courses: GradeListCourse[]; gpa: Gpas; cumulative: Gpas }

export interface GradeList {
  student: { name: string; roll: string } | null
  curriculum: string | null
  nonGpa: string[]
  terms: GradeListTerm[]
  cumulative: Gpas
}

const norm = (s: string) => s.replace(/\s+/g, '').toLowerCase()

export function gradeList(store: RecordStore, nonGpa: readonly string[]): GradeList {
  const rows = store.transcript?.rows ?? []
  const g10 = computeGpaOn('10', { rows, nonGpa })
  const g4 = computeGpaOn('4', { rows, nonGpa })
  const sem = (g: typeof g10, name: string) => g.semesters.find((s) => norm(s.name) === norm(name))
  const through = (name: string): Gpas => {
    const upto = rows.filter((r) => semesterOrder(r.semester) <= semesterOrder(name))
    const a = computeGpaOn('10', { rows: upto, nonGpa })
    const b = computeGpaOn('4', { rows: upto, nonGpa })
    return { ten: a.cumulative, four: b.cumulative, credits: a.credits }
  }
  const terms = recordTerms(store).filter((t) => t.courses.length > 0).reverse().map((t): GradeListTerm => {
    const a = sem(g10, t.name)
    return {
      name: t.name,
      courses: t.courses.map((c) => ({
        code: c.code, name: c.name, credits: c.credits, grade: c.grade, letter: letterOf(c.grade), points: pointsOf(c.grade), status: c.status,
        counted: !!c.row && g10.counted.has(c.row.id),
        average: c.sheet?.sheet.summary.average ?? null, sheetStatus: sheetStatusText(c.sheet?.sheet.summary.status), components: components(c.sheet?.sheet),
      })),
      gpa: { ten: a?.gpa ?? null, four: sem(g4, t.name)?.gpa ?? null, credits: a?.credits ?? 0 },
      cumulative: through(t.name),
    }
  })
  return { student: store.student, curriculum: store.curriculum, nonGpa: [...nonGpa], terms, cumulative: { ten: g10.cumulative, four: g4.cumulative, credits: g10.credits } }
}

/** Two decimals, half up; null as an empty value. */
export const gpaText = (g: number | null) => (g === null ? null : (Math.round(g * 100 + Number.EPSILON) / 100).toFixed(2))
export const onScale = (g: Gpas, scale: GpaScale) => (scale === '4' ? g.four : g.ten)

// ---- export --------------------------------------------------------------------------------------

export interface RecordExport extends GradeList {
  formatVersion: 1
  exportedAt: string
  note: string
}

export const buildRecordExport = (store: RecordStore, nonGpa: readonly string[], now = new Date()): RecordExport =>
  ({ formatVersion: 1, exportedAt: now.toISOString(), note: NOT_OFFICIAL, ...gradeList(store, nonGpa) })

const line = (cells: (string | number | null | undefined)[]) => cells.map(csvCell).join(',')

export function recordCsv(e: RecordExport): string {
  const out = [
    line(['FAP-AIO academic record']),
    line([e.note]),
    line(['Exported', e.exportedAt]),
    line(['Student', e.student?.name ?? '', 'Roll number', e.student?.roll ?? '']),
    line(['Curriculum', e.curriculum ?? '']),
    line(['Not counted in GPA', e.nonGpa.join(', ')]),
    line(['Cumulative GPA (10-point)', gpaText(e.cumulative.ten) ?? '', 'Cumulative GPA (4-point)', gpaText(e.cumulative.four) ?? '', 'Counted credits', e.cumulative.credits]),
    '',
    line(['Term', 'GPA (10-point)', 'GPA (4-point)', 'Counted credits', 'Cumulative GPA (10-point)', 'Cumulative GPA (4-point)']),
    ...e.terms.map((t) => line([t.name, gpaText(t.gpa.ten), gpaText(t.gpa.four), t.gpa.credits, gpaText(t.cumulative.ten), gpaText(t.cumulative.four)])),
    '',
    line(['Term', 'Subject code', 'Subject name', 'Credits', 'Grade', 'Letter', '4-point value', 'Status', 'Counted in GPA', 'Mark sheet average', 'Mark sheet status']),
    ...e.terms.flatMap((t) => t.courses.map((c) => line([t.name, c.code, c.name, c.credits, c.grade, c.letter, c.points, c.status, c.counted ? 'Yes' : 'No', c.average, c.sheetStatus]))),
    '',
    line(['Term', 'Subject code', 'Category', 'Item', 'Weight', 'Value']),
    ...e.terms.flatMap((t) => t.courses.flatMap((c) => c.components.map((x) => line([t.name, c.code, x.category, x.item, x.weight, x.value])))),
  ]
  return BOM + out.join('\r\n') + '\r\n'
}

export const recordJson = (e: RecordExport) => JSON.stringify(e, null, 2)

export const recordFileName = (format: 'csv' | 'json', now = new Date(), what = 'record') => `fap-aio-${what}-${now.toISOString().slice(0, 10)}.${format}`

/** Starts a download from a blob link inside the panel. */
export function downloadText(container: Node, name: string, text: string, type: string): void {
  const url = URL.createObjectURL(new Blob([text], { type }))
  const a = document.createElement('a')
  a.href = url
  a.download = name
  a.hidden = true
  container.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 10_000)
}
